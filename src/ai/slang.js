/** Cari kata slang di teks, kembalikan daftar "kata = arti". */
export function glossFor(text) {
  const words = new Set(
    String(text || '')
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, ' ')
      .split(/\s+/)
      .filter(Boolean),
  );

  const found = [];
  for (const w of words) {
    if (SLANG[w]) found.push(`"${w}" = ${SLANG[w]}`);
  }
  return found.slice(0, 12);
}
